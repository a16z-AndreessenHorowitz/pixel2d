import { ethers, network, artifacts } from 'hardhat'
import fs from 'fs'
import path from 'path'

async function main() {
  console.log(`\n🚀 Starting Deployment on network: [${network.name}] (ChainId: ${(await ethers.provider.getNetwork()).chainId})`)

  const [deployer] = await ethers.getSigners()
  console.log(`👤 Deployer Address: ${deployer.address}`)
  const balance = await ethers.provider.getBalance(deployer.address)
  console.log(`💰 Deployer Balance: ${ethers.formatEther(balance)} ETH\n`)

  // Hardhat Account #0 is backend signer by default, or configured via env
  const backendSignerAddress =
    process.env.BACKEND_SIGNER_ADDRESS || deployer.address
  console.log(`🔑 Backend Signer Address: ${backendSignerAddress}`)

  // 1. Deploy PixelFarmToken
  console.log('Deploying PixelFarmToken ($PIXEL)...')
  const TokenFactory = await ethers.getContractFactory('PixelFarmToken')
  const pixelToken = await TokenFactory.deploy(deployer.address, backendSignerAddress)
  await pixelToken.waitForDeployment()
  const pixelTokenAddress = await pixelToken.getAddress()
  console.log(`✅ PixelFarmToken deployed at: ${pixelTokenAddress}`)

  // 2. Deploy FarmItemNFT
  console.log('\nDeploying FarmItemNFT...')
  const baseURI = 'https://api.pixel2d.game/metadata/items/'
  const NFTFactory = await ethers.getContractFactory('FarmItemNFT')
  const farmNft = await NFTFactory.deploy(deployer.address, pixelTokenAddress, baseURI)
  await farmNft.waitForDeployment()
  const farmNftAddress = await farmNft.getAddress()
  console.log(`✅ FarmItemNFT deployed at: ${farmNftAddress}`)

  // 3. Grant BURNER_ROLE to FarmItemNFT
  console.log('\nGranting BURNER_ROLE to FarmItemNFT on PixelFarmToken...')
  const BURNER_ROLE = await pixelToken.BURNER_ROLE()
  const grantTx = await pixelToken.grantRole(BURNER_ROLE, farmNftAddress)
  await grantTx.wait()
  console.log('✅ BURNER_ROLE granted successfully (1-Click Minting enabled!)')

  // 4. Export ABIs & Addresses to Frontend
  const targetDir = path.resolve(__dirname, '../../front_end/src/web3/abis')
  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true })
  }

  const tokenArtifact = artifacts.readArtifactSync('PixelFarmToken')
  const nftArtifact = artifacts.readArtifactSync('FarmItemNFT')

  // Write standalone JSON ABIs
  fs.writeFileSync(
    path.join(targetDir, 'PixelFarmToken.json'),
    JSON.stringify(tokenArtifact.abi, null, 2),
  )
  fs.writeFileSync(
    path.join(targetDir, 'FarmItemNFT.json'),
    JSON.stringify(nftArtifact.abi, null, 2),
  )

  // Write TypeScript config module
  const tsContent = `// Auto-generated by Hardhat deploy script
// Network: ${network.name} | Timestamp: ${new Date().toISOString()}

export const CONTRACT_ADDRESSES = {
  PIXEL_TOKEN: '${pixelTokenAddress}',
  FARM_ITEM_NFT: '${farmNftAddress}',
} as const

export const PIXEL_TOKEN_ABI = ${JSON.stringify(tokenArtifact.abi, null, 2)} as const

export const FARM_ITEM_NFT_ABI = ${JSON.stringify(nftArtifact.abi, null, 2)} as const

export const CHAIN_CONFIG = {
  chainId: Number(${(await ethers.provider.getNetwork()).chainId}),
  networkName: '${network.name}',
} as const
`

  fs.writeFileSync(path.join(targetDir, 'contracts.ts'), tsContent)
  console.log(`\n📁 Exported ABI and Contract Addresses to:\n   -> ${path.join(targetDir, 'contracts.ts')}`)
  console.log(`   -> ${path.join(targetDir, 'PixelFarmToken.json')}`)
  console.log(`   -> ${path.join(targetDir, 'FarmItemNFT.json')}`)

  console.log('\n🎉 SMART CONTRACTS DEPLOYMENT COMPLETED SUCCESSFULLY!\n')
}

main().catch((err) => {
  console.error('❌ Deployment failed:', err)
  process.exit(1)
})
